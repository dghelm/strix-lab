# --- Process projection and stream exactness ---------------------------------

_OUTCOME_NAMES: dict[ProcessOutcome, ProcessOutcomeLiteral] = {
    ProcessOutcome.EXITED: "exited",
    ProcessOutcome.TIMED_OUT: "timed_out",
    ProcessOutcome.SPAWN_FAILED: "spawn_failed",
    ProcessOutcome.CAPTURE_FAILED: "capture_failed",
}


@dataclass(frozen=True, slots=True)
class _ProjectedProcess:
    projection: ProcessProjectionV1
    stdout_text: str | None
    stderr_text: str | None


def _exact_stream(text: str, byte_count: int, sha256: str, truncated: bool) -> str | None:
    """Return the publishable text of an exact stream, or ``None`` when inexact.

    A stream is exact only when it is not truncated and re-encoding the returned text
    as UTF-8 reproduces both the recorded byte count and SHA-256.
    """

    if truncated:
        return None
    encoded = text.encode("utf-8")
    if len(encoded) == byte_count and hashlib.sha256(encoded).hexdigest() == sha256:
        return text
    return None


def _project(result: ProcessResult) -> _ProjectedProcess:
    stdout_text = _exact_stream(
        result.stdout, result.stdout_bytes, result.stdout_sha256, result.stdout_truncated
    )
    stderr_text = _exact_stream(
        result.stderr, result.stderr_bytes, result.stderr_sha256, result.stderr_truncated
    )
    stdout_publishable = stdout_text is not None
    stderr_publishable = stderr_text is not None
    return _ProjectedProcess(
        projection=ProcessProjectionV1(
            outcome=_OUTCOME_NAMES[result.outcome],
            returncode=result.returncode,
            duration_seconds=max(0.0, result.duration),
            stdout_bytes=result.stdout_bytes,
            stderr_bytes=result.stderr_bytes,
            stdout_sha256=result.stdout_sha256,
            stderr_sha256=result.stderr_sha256,
            stdout_truncated=result.stdout_truncated,
            stderr_truncated=result.stderr_truncated,
            stdout_publishable=stdout_publishable,
            stderr_publishable=stderr_publishable,
            error_category=_error_category(
                result,
                stdout_publishable=stdout_publishable,
                stderr_publishable=stderr_publishable,
            ),
        ),
        stdout_text=stdout_text,
        stderr_text=stderr_text,
    )


def _error_category(
    result: ProcessResult, *, stdout_publishable: bool, stderr_publishable: bool
) -> ErrorCategory:
    if result.outcome is ProcessOutcome.CAPTURE_FAILED:
        return "capture-failed"
    if result.outcome is ProcessOutcome.SPAWN_FAILED:
        return "spawn-failed"
    if result.outcome is ProcessOutcome.TIMED_OUT:
        return "timed-out"
    if result.stdout_truncated or result.stderr_truncated:
        return "output-oversized"
    if not stdout_publishable or not stderr_publishable:
        return "encoding-failed"
    return "none"


# --- Evidence writer ----------------------------------------------------------


@dataclass(slots=True)
class _CaseEvidence:
    """Writes deterministic portable evidence under one case namespace.

    Every artifact written before the terminal sample is recorded so the sample can
    inventory it. ``sample.json`` is written through :meth:`sample` and is excluded
    from its own inventory.
    """

    run: RunSession
    base: str
    written: list[BackendOpsArtifactV1] = field(default_factory=list)

    def _publish(self, relative: str, content: bytes, *, media_type: str) -> None:
        entry = self.run.write_portable(
            f"{self.base}/{relative}", content, media_type=media_type, role=EVIDENCE_ROLE
        )
        self.written.append(
            BackendOpsArtifactV1(
                path=entry.logical_path,
                size_bytes=entry.size_bytes,
                media_type=entry.media_type,
                role=entry.role,
                sha256=entry.blob_sha256,
            )
        )

    def json(self, relative: str, value: object) -> None:
        self._publish(relative, canonical_json_bytes(value), media_type="application/json")

    def streams(
        self,
        prefix: str,
        process: _ProjectedProcess,
        *,
        sep: str,
        stdout_name: str,
        stdout_media: str,
    ) -> None:
        """Publish nonempty exact stdout/stderr text and the process projection.

        Truncated or non-UTF-8 streams have no text artifact; ``process.json`` still
        preserves their complete byte counts, digests, truncation, and neutral
        category. An exact stdout is published even when the exact stderr is not, and
        vice versa. A zero-byte exact stream carries no more than its already-recorded
        digest, so no empty text blob is written — this also keeps the shared empty
        blob from colliding across the ``text/plain`` and ``text/csv`` media types.
        """

        if process.stdout_text:
            self._publish(
                f"{prefix}{sep}{stdout_name}",
                process.stdout_text.encode("utf-8"),
                media_type=stdout_media,
            )
        if process.stderr_text:
            self._publish(
                f"{prefix}{sep}stderr.txt",
                process.stderr_text.encode("utf-8"),
                media_type="text/plain",
            )
        self.json(f"{prefix}{sep}process.json", process.projection.model_dump(mode="json"))

    def sample(self, value: object) -> None:
        """Write the terminal ``sample.json`` last, excluded from its own inventory."""

        self.run.write_portable(
            f"{self.base}/sample.json",
            canonical_json_bytes(value),
            media_type="application/json",
            role=EVIDENCE_ROLE,
        )


def _run_child(
    *,
    runner: ProcessRunner,
    argv: tuple[str, ...],
    cwd: Path,
    timeout: float,
    environment: Mapping[str, str],
    evidence: _CaseEvidence,
    prefix: str,
    sep: str,
    stdout_name: str,
    stdout_media: str,
) -> _ProjectedProcess:
    result = runner(
        argv,
        cwd=cwd,
        timeout=timeout,
        inherit_env=False,
        base_env=environment,
        output_limit_bytes=STREAM_LIMIT_BYTES,
    )
    projected = _project(result)
    evidence.streams(prefix, projected, sep=sep, stdout_name=stdout_name, stdout_media=stdout_media)
    return projected


# --- Capability and test-child classification ---------------------------------

# Process-defect precedence shared by both probes; ties select help before list-ops.
_PROBE_DEFECT_ORDER: tuple[ErrorCategory, ...] = (
    "capture-failed",
    "spawn-failed",
    "timed-out",
    "output-oversized",
    "encoding-failed",
)
_DEFECT_STATUS: dict[ErrorCategory, SampleStatus] = {
    "capture-failed": "capture-failed",
    "spawn-failed": "spawn-failed",
    "timed-out": "timed-out",
    "output-oversized": "oversized-output",
    "encoding-failed": "encoding-failed",
}


def _probe_defect(
    help_projection: ProcessProjectionV1, list_projection: ProcessProjectionV1
) -> SampleStatus | None:
    for category in _PROBE_DEFECT_ORDER:
        if help_projection.error_category == category:
            return _DEFECT_STATUS[category]
        if list_projection.error_category == category:
            return _DEFECT_STATUS[category]
    return None


def _probe_streams_clean(projection: ProcessProjectionV1) -> bool:
    """A probe's streams are clean when stdout is exact and stderr is exact and empty."""

    return (
        projection.stdout_publishable
        and projection.stderr_publishable
        and projection.stderr_bytes == 0
    )


def _evaluate_capability(
    help_process: _ProjectedProcess,
    list_process: _ProjectedProcess,
    *,
    case: BackendOpsCaseV1,
    binary_sha256: str,
) -> tuple[SampleStatus | None, CapabilityReason | None, BackendOpsCapabilitiesV1 | None]:
    """Decide whether both probes prove the pinned capability profile.

    Returns a terminal process-defect status (no reason), or a ``capability-failed``
    status with a refining reason, or ``(None, None, capabilities)`` when discovered.
    """

    defect = _probe_defect(help_process.projection, list_process.projection)
    if defect is not None:
        return defect, None, None

    help_projection = help_process.projection
    if help_projection.returncode != 1:
        return "capability-failed", "help-exit", None
    if not _probe_streams_clean(help_projection):
        return "capability-failed", "help-stream", None
    if not parse_help_grammar(help_process.stdout_text or ""):
        return "capability-failed", "help-grammar", None

    list_projection = list_process.projection
    if list_projection.returncode != 0:
        return "capability-failed", "list-exit", None
    if not _probe_streams_clean(list_projection):
        return "capability-failed", "list-stream", None
    try:
        operations = parse_operations(list_process.stdout_text or "")
    except BackendOpsGrammarError:
        return "capability-failed", "list-grammar", None

    advertised = set(operations)
    if any(operation not in advertised for operation in case.operations):
        return "capability-failed", "operation-absent", None

    capabilities = BackendOpsCapabilitiesV1(binary_sha256=binary_sha256, operations=operations)
    return None, None, capabilities


def _classify_test(
    test_process: _ProjectedProcess, *, case: BackendOpsCaseV1
) -> tuple[SampleStatus, tuple[BackendOpsRowV1, ...] | None, BackendOpsGateSummaryV1 | None]:
    """Map the test child's outcome to a terminal status, retained rows, and gate.

    Independently exact stdout is always parsed and its rows retained, even when
    stderr is defective or the child exits nonzero. A process defect on *either*
    stream (capture, spawn, timeout, oversized, invalid UTF-8) outranks child, parse,
    and gate outcomes and forbids a pass, matching the hard-gate condition that a
    passing case has no truncation/encoding defect; a nonzero exit (``child-failed``)
    then wins over parse and gate outcomes.
    """

    projection = test_process.projection

    rows: tuple[BackendOpsRowV1, ...] | None = None
    if projection.stdout_publishable and not projection.stdout_truncated:
        try:
            rows = parse_csv_rows(test_process.stdout_text or "", case=case)
        except BackendOpsParseError:
            rows = None

    if projection.error_category != "none":
        return _DEFECT_STATUS[projection.error_category], rows, None
    if projection.returncode != 0:
        return "child-failed", rows, None
    if rows is None:
        return "parse-failed", None, None
    gate = evaluate_gate(rows, case=case)
    if gate.passed:
        return "passed", rows, gate
    return "hard-gate-failed", rows, gate


# --- Orchestration ------------------------------------------------------------


def run_backend_ops_case(
    *,
    case: BackendOpsCaseV1,
    inputs: BackendOpsInputsV1,
    run: RunSession,
    environment: Mapping[str, str],
    cwd: Path,
    capability_timeout: float,
    test_timeout: float,
    runner: ProcessRunner = run_process,
) -> BackendOpsSampleV1:
    """Execute one correctness case and return its terminal versioned sample.

    Two bounded capability probes and (on capability success) one test child run
    against ``environment`` with ``inherit_env=False`` and an explicit ``cwd``. Binary
    identity is verified before each child and re-verified after the terminal child;
    drift raises :class:`BackendOpsIntegrityError` and leaves no ``sample.json``.
    Ordinary capability, process, parse, and hard-gate failures return a structured
    sample. The caller owns ``run``: this adapter never finalizes it.
    """

    binary_path = Path(inputs.binary_path)
    evidence = _CaseEvidence(run=run, base=f"{EVIDENCE_ROOT}/{case.id}")

    identity = _hash_binary(binary_path)
    if identity.sha256 != inputs.binary_sha256:
        raise BackendOpsIntegrityError("operations binary SHA-256 does not match the input binding")

    # Probe 1: --help. The initial hash snapshot is its integrity check.
    help_process = _run_child(
        runner=runner,
        argv=(str(binary_path), "--help"),
        cwd=cwd,
        timeout=capability_timeout,
        environment=environment,
        evidence=evidence,
        prefix="capabilities/help",
        sep=".",
        stdout_name="stdout.txt",
        stdout_media="text/plain",
    )

    # Probe 2: --list-ops. Always attempted unless intervening drift aborts.
    _require_stable_binary(binary_path, identity)
    list_process = _run_child(
        runner=runner,
        argv=(str(binary_path), "--list-ops"),
        cwd=cwd,
        timeout=capability_timeout,
        environment=environment,
        evidence=evidence,
        prefix="capabilities/list-ops",
        sep=".",
        stdout_name="stdout.txt",
        stdout_media="text/plain",
    )

    status, reason, capabilities = _evaluate_capability(
        help_process, list_process, case=case, binary_sha256=inputs.binary_sha256
    )
    attempt = BackendOpsCapabilityAttemptV1(
        status="failed" if capabilities is None else "discovered",
        reason=reason,
        help=help_process.projection,
        list_ops=list_process.projection,
        capabilities=capabilities,
    )
    evidence.json("capabilities/attempt.json", attempt.model_dump(mode="json"))

    if capabilities is None:
        assert status is not None
        _require_stable_binary(binary_path, identity)
        return _finalize(
            evidence,
            status=status,
            reason=reason,
            case=case,
            inputs=inputs,
            attempt=attempt,
            invocation=None,
            rows=None,
            gate=None,
        )

    # Test child.
    argv = build_test_argv(binary_path=str(binary_path), case=case)
    _require_stable_binary(binary_path, identity)
    test_process = _run_child(
        runner=runner,
        argv=argv,
        cwd=cwd,
        timeout=test_timeout,
        environment=environment,
        evidence=evidence,
        prefix="invocations/0001",
        sep="/",
        stdout_name="stdout.csv",
        stdout_media="text/csv",
    )

    # Re-verify identity after the terminal child. Drift leaves no sample.json.
    _require_stable_binary(binary_path, identity)

    invocation = BackendOpsInvocationV1(ordinal=1, argv=argv, process=test_process.projection)
    test_status, rows, gate = _classify_test(test_process, case=case)
    return _finalize(
        evidence,
        status=test_status,
        reason=None,
        case=case,
        inputs=inputs,
        attempt=attempt,
        invocation=invocation,
        rows=rows,
        gate=gate,
    )


def _finalize(
    evidence: _CaseEvidence,
    *,
    status: SampleStatus,
    reason: CapabilityReason | None,
    case: BackendOpsCaseV1,
    inputs: BackendOpsInputsV1,
    attempt: BackendOpsCapabilityAttemptV1,
    invocation: BackendOpsInvocationV1 | None,
    rows: tuple[BackendOpsRowV1, ...] | None,
    gate: BackendOpsGateSummaryV1 | None,
) -> BackendOpsSampleV1:
    """Build the sample from already-written evidence and publish ``sample.json`` last."""

    sample = BackendOpsSampleV1(
        status=status,
        reason=reason,
        case=case,
        inputs=inputs,
        capability_attempt=attempt,
        capabilities=attempt.capabilities,
        invocation=invocation,
        rows=rows,
        gate=gate,
        artifacts=tuple(sorted(evidence.written, key=lambda artifact: artifact.path)),
    )
    evidence.sample(sample.model_dump(mode="json"))
    return sample
