"""Bounded ``test-backend-ops`` correctness hard-gate adapter for one typed case.

This adapter executes a verified ``test-backend-ops`` binary for exactly one filtered
set of operations against one named backend, parses the pinned ca94157 CSV result
grammar, applies a fail-closed correctness hard gate, and returns one versioned
:class:`BackendOpsSampleV1` through the caller-owned :class:`RunSession`. The grammar
is pinned to ``halo-box/strix-llama.cpp@ca94157f70a2776e8da6b6849b50b45a083d0478``
built with ``LLAMA_BUILD_TESTS=ON``.

Its only policy decision is fail-closed correctness: every selected case must be
exercised, supported, and free of an error message, and the child must exit
successfully. It defines no suite manifest, operation-set policy, ranking, or run
command; later layers call this adapter. It never acquires the GPU lock and never
finalizes the caller-owned ``RunSession``.
"""

