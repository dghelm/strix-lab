class BackendOpsSampleV1(_Model):
    """The terminal, versioned adapter sample for one correctness case."""

    schema_version: Literal[1] = 1
    profile: Literal["ca94157-v1"] = PROFILE
    status: SampleStatus
    reason: CapabilityReason | None
    case: BackendOpsCaseV1
    inputs: BackendOpsInputsV1
    capability_attempt: BackendOpsCapabilityAttemptV1
    capabilities: BackendOpsCapabilitiesV1 | None
    invocation: BackendOpsInvocationV1 | None
    rows: tuple[BackendOpsRowV1, ...] | None
    gate: BackendOpsGateSummaryV1 | None
    artifacts: tuple[BackendOpsArtifactV1, ...]

    @model_validator(mode="after")
    def _consistent(self) -> Self:
        if self.capabilities != self.capability_attempt.capabilities:
            raise ValueError("sample capabilities must mirror the capability attempt")
        if self.reason != self.capability_attempt.reason:
            raise ValueError("sample reason must mirror the capability attempt reason")
        if (self.reason is not None) != (self.status == "capability-failed"):
            raise ValueError("a reason refines exactly a capability failure")
        # ``capabilities`` presence already follows from the mirror above and the
        # attempt's own discovered-iff-capabilities invariant, so only the
        # invocation and status couplings remain to check here.
        discovered = self.capability_attempt.status == "discovered"
        if discovered != (self.invocation is not None):
            raise ValueError("an invocation exists exactly when capabilities were discovered")
        if not discovered and self.status in _TEST_ONLY_STATUSES:
            raise ValueError("a test-child status requires discovered capabilities")
        if (
            self.status in _TEST_ONLY_STATUSES
            and self.invocation is not None
            and self.invocation.process.error_category != "none"
        ):
            raise ValueError("a post-parse status requires a test process with no defect")
        if self.status in ("passed", "hard-gate-failed"):
            if self.gate is None or self.rows is None:
                raise ValueError("a gated sample binds rows and a gate summary")
            if (self.status == "passed") != self.gate.passed:
                raise ValueError("gate.passed must agree with the passed status")
        elif self.gate is not None:
            raise ValueError("only a gated sample carries a gate summary")
        if self.status == "parse-failed" and self.rows is not None:
            raise ValueError("a parse-failed sample retains no rows")
        return self


# --- Pure command builder -----------------------------------------------------


def build_test_argv(*, binary_path: str, case: BackendOpsCaseV1) -> tuple[str, ...]:
    """Return the only allowlisted argv for one test-mode CSV invocation.

    Every value is read from the typed case, so injection-shaped ``params_regex`` or
    backend values remain single argv data items and never become shell text.
    """

    # Fully revalidate the case, rejecting any value (operations, backend, regex, or the
    # fixed mode/output/workers) that cannot round-trip through the typed case — for
    # example a case built via ``model_construct`` that bypassed validation.
    try:
        BackendOpsCaseV1.model_validate(case.model_dump())
    except ValidationError as exc:
        raise ValueError("case does not round-trip to the pinned test-mode invocation") from exc
    return (
        binary_path,
        "test",
        "-o",
        ",".join(case.operations),
        "-b",
        case.backend,
        "-p",
        case.params_regex,
        "--output",
        "csv",
        "-j",
        "1",
    )


# --- Pure capability parsers --------------------------------------------------


def _help_token_lines(text: str) -> tuple[tuple[str, ...], ...]:
    """Tokenize each nonempty stripped help line at whitespace boundaries."""

    lines: list[tuple[str, ...]] = []
    for raw in text.splitlines():
        stripped = raw.strip()
        if stripped:
            lines.append(tuple(stripped.split()))
    return tuple(lines)


_PINNED_HELP_TOKENS = _help_token_lines(_PINNED_HELP_TEXT)


def parse_help_grammar(help_stdout: str) -> bool:
    """Return whether ``help_stdout`` matches the pinned ca94157 usage grammar.

    Only the single non-whitespace program-path token after ``Usage:`` is normalized;
    every other token must match the pinned grammar exactly. Suffix, substring,
    reordered-option, and weakened-choice lookalikes therefore fail.
    """

    observed = _help_token_lines(help_stdout)
    if not observed:
        return False
    first = observed[0]
    if len(first) < 2 or first[0] != "Usage:":
        return False
    normalized_first = (first[0], _PINNED_HELP_TOKENS[0][1]) + first[2:]
    return ((normalized_first, *observed[1:])) == _PINNED_HELP_TOKENS


def parse_operations(list_stdout: str) -> tuple[str, ...]:
    """Parse the exact ca94157 ``--list-ops`` header/list/blank/total grammar.

    Requires exactly ``EXPECTED_OPERATION_COUNT`` unique two-space-indented uppercase
    operation lines and the matching ``Total`` line; any drift raises
    :class:`BackendOpsGrammarError` rather than silently forward-compatible parsing.
    """

    if "\r" in list_stdout or not list_stdout.endswith("\n"):
        raise BackendOpsGrammarError("operation list has an unexpected line ending")
    # The trailing newline guarantees a final empty split element to drop.
    lines = list_stdout.split("\n")[:-1]
    if len(lines) != EXPECTED_OPERATION_COUNT + 3:
        raise BackendOpsGrammarError("operation list has an unexpected line count")
    if lines[0] != "GGML operations:":
        raise BackendOpsGrammarError("operation list is missing its header")
    if lines[EXPECTED_OPERATION_COUNT + 1] != "":
        raise BackendOpsGrammarError("operation list is missing its blank separator")
    if lines[EXPECTED_OPERATION_COUNT + 2] != f"Total: {EXPECTED_OPERATION_COUNT} operations":
        raise BackendOpsGrammarError("operation list has an unexpected total line")
    operations: list[str] = []
    seen: set[str] = set()
    for line in lines[1 : EXPECTED_OPERATION_COUNT + 1]:
        name = line[2:]
        if line != "  " + name or re.fullmatch(r"[A-Z][A-Z0-9_]*", name) is None:
            raise BackendOpsGrammarError("operation list has a malformed operation line")
        if name in seen:
            raise BackendOpsGrammarError("operation list has a duplicate operation")
        seen.add(name)
        operations.append(name)
    return tuple(operations)


# --- Pure CSV parser ----------------------------------------------------------


def parse_csv_rows(stdout: str, *, case: BackendOpsCaseV1) -> tuple[BackendOpsRowV1, ...]:
    """Parse and structurally validate one test-mode CSV output, preserving row order.

    Uses the standard-library reader in strict mode over complete UTF-8 stdout and
    rejects a wrong header, malformed quoting or column counts, blank or newline-
    bearing records, trailing content, control characters, an out-of-range row count,
    a non-``test`` mode, an unrequested operation, a mismatched or empty backend, a
    non-pinned ``supported`` value, and duplicate rows. Any ``csv.Error`` (including
    the default field-size limit) becomes a domain parse error.
    """

    if "\r" in stdout:
        raise BackendOpsParseError("CSV output contains a carriage return")
    reader = csv.reader(io.StringIO(stdout, newline=""), strict=True)
    try:
        records = list(reader)
    except csv.Error as exc:
        raise BackendOpsParseError("CSV output is malformed") from exc
    if not records:
        raise BackendOpsParseError("CSV output is empty")
    header, *data = records
    if tuple(header) != CSV_HEADER:
        raise BackendOpsParseError("CSV header does not match the pinned columns")
    if not data:
        raise BackendOpsParseError("CSV output has zero result rows")
    if len(data) > MAX_RESULT_ROWS:
        raise BackendOpsParseError("CSV output exceeds the maximum row count")

    requested = set(case.operations)
    seen: set[tuple[str, ...]] = set()
    rows: list[BackendOpsRowV1] = []
    for record in data:
        if record == []:
            raise BackendOpsParseError("CSV output contains a blank record")
        if len(record) != len(CSV_HEADER):
            raise BackendOpsParseError("CSV row has the wrong column count")
        for field_value in record:
            if any(ord(ch) < 0x20 or ord(ch) == 0x7F for ch in field_value):
                raise BackendOpsParseError("CSV field contains a control character")
        identity = tuple(record)
        if identity in seen:
            raise BackendOpsParseError("CSV output contains a duplicate row")
        seen.add(identity)
        (backend_name, op_name, op_params, test_mode, supported, error_message, reg_name) = record
        if test_mode != "test":
            raise BackendOpsParseError("CSV row is not a test-mode row")
        if op_name not in requested:
            raise BackendOpsParseError("CSV row reports an unrequested operation")
        if backend_name == "" or backend_name != case.backend:
            raise BackendOpsParseError("CSV row backend does not match the requested backend")
        if supported not in ("0", "1"):
            raise BackendOpsParseError("CSV row has a non-pinned supported value")
        rows.append(
            BackendOpsRowV1(
                backend_name=backend_name,
                op_name=op_name,
                op_params=op_params,
                test_mode=test_mode,
                supported=cast(Literal["0", "1"], supported),
                error_message=error_message,
                backend_reg_name=reg_name,
            )
        )
    return tuple(rows)


# --- Pure hard-gate policy ----------------------------------------------------


def evaluate_gate(
    rows: tuple[BackendOpsRowV1, ...], *, case: BackendOpsCaseV1
) -> BackendOpsGateSummaryV1:
    """Decide fail-closed correctness over already-parsed rows.

    A case passes only when there is at least one row, every row binds the requested
    backend and test mode, every requested operation appears in at least one row,
    every row is supported (``"1"``), and every ``error_message`` is empty.
    """

    observed_backends: list[str] = []
    for row in rows:
        if row.backend_name not in observed_backends:
            observed_backends.append(row.backend_name)
    reason = _gate_reason(rows, case)
    return BackendOpsGateSummaryV1(
        selected_count=len(case.operations),
        observed_rows=len(rows),
        observed_backends=tuple(observed_backends),
        passed=reason == "passed",
        reason=reason,
    )


def _gate_reason(rows: tuple[BackendOpsRowV1, ...], case: BackendOpsCaseV1) -> GateReason:
    if not rows:
        return "no-rows"
    if any(row.backend_name != case.backend for row in rows):
        return "wrong-backend"
    if any(row.test_mode != "test" for row in rows):
        return "wrong-mode"
    observed_operations = {row.op_name for row in rows}
    if any(operation not in observed_operations for operation in case.operations):
        return "missing-operation"
    if any(row.supported != "1" for row in rows):
        return "unsupported-row"
    if any(row.error_message != "" for row in rows):
        return "error-bearing-row"
    return "passed"


