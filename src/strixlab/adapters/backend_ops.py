def _validate_case_id(value: str) -> str:
    if not (1 <= len(value) <= 64):
        raise ValueError("case id must be 1 to 64 characters")
    return value


def _validate_params_regex(value: str) -> str:
    if not value:
        raise ValueError("params_regex must be non-empty")
    if len(value.encode("utf-8")) > 512:
        raise ValueError("params_regex exceeds 512 UTF-8 bytes")
    if any(ord(character) < 0x20 or ord(character) == 0x7F for character in value):
        raise ValueError("params_regex must not contain C0 or DEL control characters")
    return value


def _validate_backend(value: str) -> str:
    if not (1 <= len(value) <= 128):
        raise ValueError("backend must be 1 to 128 characters")
    if any(not (0x20 <= ord(character) <= 0x7E) for character in value):
        raise ValueError("backend must be printable ASCII")
    return value


def _validate_build_id(value: str) -> str:
    encoded = value.encode("utf-8")
    if not (1 <= len(encoded) <= 256):
        raise ValueError("build_id must be 1 to 256 UTF-8 bytes")
    if any(ord(character) < 0x20 or ord(character) == 0x7F for character in value):
        raise ValueError("build_id must not contain C0 or DEL control characters")
    return value


